#!/usr/bin/env python3
"""Audit GDT 3D assets and catalog; write JSON + Markdown reports under docs/."""

from __future__ import annotations

import json
import statistics
from datetime import date
from pathlib import Path

import trimesh

ROOT = Path(__file__).resolve().parents[2]
GLB = ROOT / "apps" / "web" / "public" / "assets" / "galveston" / "galveston-demo.glb"
CATALOG = ROOT / "apps" / "web" / "public" / "assets" / "galveston" / "buildings-catalog.json"
STUDY = ROOT / "config" / "study_area.json"
OUT_JSON = ROOT / "docs" / "geometry-audit-report.json"
OUT_MD = ROOT / "docs" / "GEOMETRY-AUDIT.md"


def analyze_glb(path: Path) -> dict:
    loaded = trimesh.load(path, force="scene")
    if isinstance(loaded, trimesh.Scene):
        geoms = list(loaded.geometry.values())
        bounds = loaded.bounds
    else:
        geoms = [loaded]
        bounds = loaded.bounds

    verts = sum(len(g.vertices) for g in geoms)
    faces = sum(len(g.faces) for g in geoms)
    ext = bounds[1] - bounds[0]
    return {
        "path": str(path.relative_to(ROOT)),
        "size_bytes": path.stat().st_size,
        "mesh_count": len(geoms),
        "vertex_count": verts,
        "face_count": faces,
        "bounds_local_m": {
            "min": bounds[0].tolist(),
            "max": bounds[1].tolist(),
            "extent_xyz_m": ext.tolist(),
        },
        "note": "OSM2World exports Y-up local ENU meters about study centroid; not per-building GLB nodes.",
    }


def analyze_catalog(path: Path) -> dict:
    data = json.loads(path.read_text(encoding="utf-8"))
    buildings = data["buildings"]
    heights = [b["height_m"] for b in buildings]
    sources: dict[str, int] = {}
    for b in buildings:
        key = b.get("height_source", "unknown")
        sources[key] = sources.get(key, 0) + 1
    areas = [b.get("footprint_area_m2", 0) for b in buildings]
    return {
        "path": str(path.relative_to(ROOT)),
        "building_count": len(buildings),
        "height_m": {
            "min": min(heights),
            "max": max(heights),
            "mean": statistics.mean(heights),
            "stdev": statistics.pstdev(heights) if len(heights) > 1 else 0,
        },
        "height_source_counts": sources,
        "footprint_area_m2": {
            "min": min(areas),
            "max": max(areas),
            "mean": statistics.mean(areas),
        },
        "lod_assigned": "LOD1 (OSM footprint + OSM2World procedural walls/roofs)",
        "per_building_mesh_in_glb": False,
    }


def render_markdown(report: dict) -> str:
    g = report["glb"]
    c = report["catalog"]
    s = report["study_area"]
    return f"""# Galveston Digital Twin — geometry audit

Date: {report["generated_on"]}. Generated by `geospatial/validation/audit_geometry.py`.

## Executive summary

The demonstration environment is **real 3D mesh geometry** (OSM2World GLB) draped on **2D satellite/aerial imagery**. Satellite pixels show **photographed rooftops and facades**; they are **not** 3D structure. The GLB is a **single merged asset** ({g["mesh_count"]} internal meshes) without stable per-building mesh IDs in the viewer, so selection uses the **566-entry footprint catalog**, not ray hits on individual OSM2World meshes.

## Asset inventory

| Asset | Detail |
|-------|--------|
| Reconstruction GLB | `{g["path"]}` — {g["size_bytes"] / 1e6:.2f} MB |
| Meshes (internal) | {g["mesh_count"]} |
| Vertices / faces | {g["vertex_count"]:,} / {g["face_count"]:,} |
| Local extent (m) | X {g["bounds_local_m"]["extent_xyz_m"][0]:.1f}, Y {g["bounds_local_m"]["extent_xyz_m"][1]:.1f}, Z {g["bounds_local_m"]["extent_xyz_m"][2]:.1f} |
| Building catalog | {c["building_count"]} footprints |
| Height range (catalog) | {c["height_m"]["min"]:.1f}–{c["height_m"]["max"]:.1f} m (mean {c["height_m"]["mean"]:.2f} m) |
| Height sources | {json.dumps(c["height_source_counts"])} |

## What is 3D vs imagery-only

| Feature | Representation |
|---------|----------------|
| Building walls / roofs (generated) | 3D mesh in GLB (LOD 1 procedural) |
| Roads / ground in GLB | 3D mesh (can obscure satellite — opacity toggle in UI) |
| Photographed buildings in satellite | **Imagery only** (2D texture on globe) |
| Terrain (default without Ion) | WGS84 **ellipsoid** |
| Terrain (with Cesium ion token) | **Cesium World Terrain** (not yet TNRIS/3DEP local DEM) |
| Per-building pick on mesh | **Not available** (monolithic GLB) |
| Street-level camera | **Supported** (presets + walk mode); **no building collision** |

## Quality levels (planned vs current)

| LOD | Status |
|-----|--------|
| LOD 1 — OSM + OSM2World | **Deployed** (this GLB) |
| LOD 2 — LiDAR heights, refined roofs | **Pipeline stub** — see `geospatial/terrain/` and catalog height sources |
| LOD 3 — Photogrammetry / licensed meshes | **Not integrated** — requires data acquisition & licensing review |

## Known visual conflicts

1. **Double rooftops**: satellite shows real roofs; GLB draws procedural roofs above the same footprint.
2. **Height homogeneity**: {c["height_source_counts"].get("estimated:default", 0)} / {c["building_count"]} buildings use default height estimate.
3. **Ground mesh opacity**: full GLB opacity affects buildings and ground together until mesh groups are split in export.

## Study area

- Name: {s["name"]}
- Bbox: W {s["bbox_wgs84"]["west"]}, S {s["bbox_wgs84"]["south"]}, E {s["bbox_wgs84"]["east"]}, N {s["bbox_wgs84"]["north"]}
- Local ENU anchor: {s["local_origin_wgs84"]["latitude"]}, {s["local_origin_wgs84"]["longitude"]}

## Recommendations (execution plan alignment)

1. **Phase B**: Local DEM from USGS 3DEP / TNRIS → Cesium terrain tile or custom layer; validate vertical datum (NAVD88 vs ellipsoid).
2. **Phase C**: Per-building export (3D Tiles or multi-GLB) with IDs; LiDAR height refinement for demo district blocks.
3. **Phase D**: Walk navigation with terrain clamp; document lack of mesh collision until simplified colliders exist.
4. **Phase E**: Export collision prisms from catalog (`geospatial/export/simulation_geometry.py`).
5. **Phase F**: High-fidelity **demo district** polygon in `config/demo_district.json` (subset of study area).

See also `docs/IMMERSIVE-3D-ROADMAP.md` and `docs/UNREAL-INTEGRATION.md`.
"""


def main() -> None:
    if not GLB.exists():
        raise FileNotFoundError(GLB)
    if not CATALOG.exists():
        raise FileNotFoundError(CATALOG)

    study = json.loads(STUDY.read_text(encoding="utf-8"))
    report = {
        "generated_on": date.today().isoformat(),
        "glb": analyze_glb(GLB),
        "catalog": analyze_catalog(CATALOG),
        "study_area": {
            "name": study["name"],
            "bbox_wgs84": study["bbox_wgs84"],
            "local_origin_wgs84": study["local_origin_wgs84"],
        },
        "terrain_runtime": {
            "default": "ellipsoid",
            "with_cesium_ion_token": "Cesium.createWorldTerrainAsync()",
            "local_lidar_dem": "not_yet_integrated",
        },
    }
    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(json.dumps(report, indent=2), encoding="utf-8")
    OUT_MD.write_text(render_markdown(report), encoding="utf-8")
    print(f"Wrote {OUT_JSON} and {OUT_MD}")


if __name__ == "__main__":
    main()
